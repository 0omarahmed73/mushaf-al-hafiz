/// Five words of [data]: the first, the last and three between them.
List<int> sampleWords(PageData data) {
  final ids = [
    for (final l in data.lines)
      for (final w in l.words) w.id,
  ];
  return [
    for (final i in [
      0,
      ids.length ~/ 4,
      ids.length ~/ 2,
      (ids.length * 3) ~/ 4,
      ids.length - 1,
    ])
      ids[i],
  ];
}

/// The rectangles this test pins, by name, as [left, top, right, bottom].
Map<String, List<double>> measure(WidgetTester t, PageData data) {
  List<double> r(Finder f) {
    final x = t.getRect(f);
    return [x.left, x.top, x.right, x.bottom];
  }

  final out = <String, List<double>>{
    'card': r(find.byType(MushafPageCard)),
    'top-bar': r(key('top-bar')),
    'page-number': r(key('page-number')),
  };
  // Every line the page has (15, or 8 on pages 1 and 2).
  for (final line in data.lines) {
    out['line-${line.number}'] = r(key('line-${line.number}'));
  }
  for (final id in sampleWords(data)) {
    out['w$id'] = r(key('w$id'));
  }
  final banners = find.byWidgetPredicate(
    (w) => w is Text && (w.data?.startsWith('سورة ') ?? false),
  );
  for (final e in banners.evaluate()) {
    final text = (e.widget as Text).data!;
    out['banner $text'] = r(find.byElementPredicate((x) => identical(x, e)));
  }
  return out;
}

String _literal(Map<String, List<double>> m) {
  String n(double v) {
    final s = v.toStringAsFixed(2);
    return s.endsWith('.00') ? s.substring(0, s.length - 3) : s;
  }

  return '{${[for (final e in m.entries) "'${e.key}': [${e.value.map(n).join(', ')}]"].join(', ')}}';
}

void expectSame(
  Map<String, List<double>> actual,
  Map<String, List<double>> expected,
  String where,
) {
  expect(
    actual.keys.toSet(),
    expected.keys.toSet(),
    reason: '$where: the measured elements',
  );
  for (final e in expected.entries) {
    for (var i = 0; i < 4; i++) {
      expect(
        actual[e.key]![i],
        closeTo(e.value[i], 0.01),
        reason:
            '$where ${e.key} edge $i: ${actual[e.key]} vs baseline ${e.value}',
      );
    }
  }
}

/// Opens the reader on [page] in [look] at [size] and measures it.
Future<Map<String, List<double>>> measureReader(
  WidgetTester t, {
  required int page,
  required LookChoice look,
  required Size size,
  Future<void> Function(WirdRepository repo, int? wirdId)? seed,
}) async {
  final mushaf = MushafRepository(rootBundle);
  final data = (await t.runAsync(() => mushaf.loadPage(page)))!;
  await pumpBookmarkReader(
    t,
    startPage: page,
    look: look,
    screen: size,
    seed: seed,
  );
  return measure(t, data);
}

void main() {
  group('baseline before feature 013 (T002)', () {
    for (final s in sizes.entries) {
      for (final l in looks.entries) {
        for (final p in pages) {
          final name = '${s.key} ${l.key} $p';
          testWidgets(name, (t) async {
            final got = await measureReader(
              t,
              page: p,
              look: l.value,
              size: s.value,
            );
            if (_print) {
              print("GEOMETRY '$name': ${_literal(got)},");
              return;
            }
            expectSame(got, baseline[name]!, name);
          });
        }
      }
    }
  });

  // T037: the same rectangles with 200 ayah bookmarks of the wird, every ayah of the measured page among them, and the tint
  // on (the default): every word of the page is drawn on the look's tint and nothing moved, to the pixel.
  group('with 200 ayah bookmarks and the tint on (T037)', () {
    for (final s in sizes.entries) {
      for (final l in looks.entries) {
        for (final p in pages) {
          final name = '${s.key} ${l.key} $p';
          testWidgets(name, (t) async {
            var seeded = 0;
            final got = await measureReader(
              t,
              page: p,
              look: l.value,
              size: s.value,
              seed: (repo, wirdId) async {
                final refs = await seedManyAyahBookmarks(
                  repo,
                  wirdId,
                  pages: pages,
                );
                seeded = refs.length;
              },
            );
            expect(seeded, 200);
            final data = (await t.runAsync(
              () => MushafRepository(rootBundle).loadPage(p),
            ))!;
            expect(wordsOn(t, l.value.pageLook.bookmarkTint), {
              for (final line in data.lines)
                for (final w in line.words) w.id,
            }, reason: '$name: every word of the page is tinted');
            expectSame(got, baseline[name]!, name);
          });
        }
      }
    }
  });
}

