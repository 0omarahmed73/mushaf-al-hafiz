const double kTolerance = 0.01;

/// The most width the index title may lose once the search icon sits in the app bar (spec FR-030).
const double kTitleShrink = 48;

/// A rectangle as `[left, top, width, height]`.
List<double> _box(Rect r) => [r.left, r.top, r.width, r.height];

String _num(double v) =>
    v.toStringAsFixed(3).replaceFirst(RegExp(r'\.?0+$'), '');

/// Prints the literal of one case (so the numbers of the baseline are copied from a run, never typed) and returns it.
String _literal(String name, Map<String, List<double>> boxes) {
  final b = StringBuffer("  '$name': {\n");
  for (final e in boxes.entries) {
    b.writeln("    '${e.key}': [${e.value.map(_num).join(', ')}],");
  }
  b.writeln('  },');
  return b.toString();
}

/// Compares [now] with the recorded [name]. The entries of [titleMayShrink] (the index title) keep their start edge (the
/// right edge: the app is right to left), their top and their height, and may lose at most [kTitleShrink] of width.
void _expectBaseline(
  String name,
  Map<String, List<double>> now, {
  Set<String> titleMayShrink = const {},
}) {
  final recorded = kBaseline[name];
  if (recorded == null) {
    // ignore: avoid_print
    print('BASELINE-LITERAL\n${_literal(name, now)}');
    fail('no baseline recorded for "$name"');
  }
  expect(
    now.keys.toSet(),
    recorded.keys.toSet(),
    reason: '$name: the set of measured things',
  );
  const parts = ['left', 'top', 'width', 'height'];
  for (final key in recorded.keys) {
    final was = recorded[key]!;
    final here = now[key]!;
    if (titleMayShrink.contains(key)) {
      expect(
        here[0] + here[2],
        closeTo(was[0] + was[2], kTolerance),
        reason: '$name / $key / start edge',
      );
      expect(
        here[1],
        closeTo(was[1], kTolerance),
        reason: '$name / $key / top',
      );
      expect(
        here[3],
        closeTo(was[3], kTolerance),
        reason: '$name / $key / height',
      );
      expect(
        here[2],
        inInclusiveRange(
          was[2] - kTitleShrink - kTolerance,
          was[2] + kTolerance,
        ),
        reason: '$name / $key / width',
      );
      continue;
    }
    for (var i = 0; i < 4; i++) {
      expect(
        here[i],
        closeTo(was[i], kTolerance),
        reason: '$name / $key / ${parts[i]}',
      );
    }
  }
}

Map<String, List<double>> _readerBoxes(WidgetTester t) {
  final boxes = <String, List<double>>{
    'top-bar': _box(t.getRect(find.byKey(const ValueKey('top-bar')))),
  };
  for (final e in pageRects(t).entries) {
    boxes[e.key] = _box(e.value);
  }
  return boxes;
}

Future<Map<String, List<double>>> _indexBoxes(
  WidgetTester t,
  LookChoice look,
  Size screen,
  double textScale,
) async {
  final app = await LookApp.create(t, choice: look);
  await app.show(t, const IndexScreen(), screen: screen, textScale: textScale);
  Rect rect(Finder f) => t.getRect(f);
  final boxes = <String, List<double>>{
    'title': _box(rect(find.text('الفهرس'))),
    'tab-surahs': _box(rect(find.text('السور'))),
    'tab-juz': _box(rect(find.text('الأجزاء'))),
    'tab-page': _box(rect(find.text('صفحة'))),
  };
  final rows = find.descendant(
    of: find.byKey(const ValueKey('surah-list')),
    matching: find.byType(ListTile),
  );
  for (var i = 0; i < 3; i++) {
    boxes['row-${i + 1}'] = _box(rect(rows.at(i)));
  }
  await t.tap(find.text('صفحة'));
  await settle(t);
  boxes['page-field'] = _box(rect(find.byKey(const ValueKey('page-field'))));
  return boxes;
}

void main() {
  group('the index screen', () {
    for (final look in [LookChoice.emerald, LookChoice.night]) {
      for (final (screen, scale, label) in [
        (const Size(412, 915), 1.0, '412x915'),
        (const Size(320, 640), 2.0, '320x640@2'),
      ]) {
        final name = 'index/${look.name}/$label';
        testWidgets(name, (t) async {
          final boxes = await _indexBoxes(t, look, screen, scale);
          // After feature 011 the search icon takes room at the end of the app bar: the title keeps its start edge and
          // its top and may lose at most 48 px of width (spec FR-030).
          _expectBaseline(name, boxes, titleMayShrink: const {'title'});
        });
      }
    }
  });

  group('the reader', () {
    for (final page in [42, 293]) {
      final name = 'reader/412x915/page-$page';
      testWidgets(name, (t) async {
        await pumpSizedReader(t, startPage: page);
        _expectBaseline(name, _readerBoxes(t));
      });
    }
  });
}

