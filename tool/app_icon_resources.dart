import 'dart:ui';

import 'package:mushaf/splash/icon_geometry.dart';
import 'package:mushaf/splash/splash_palette.dart';

/// The text of the three Android vector layers of the launcher icon, computed from [AppIconGeometry] and [SplashColors] so the
/// icon, the splash tile and the layers cannot drift apart (spec FR-004, research D5). `tool/make_app_icons.dart` writes them
/// to `android/app/src/main/res/drawable/`; `test/splash/android_icon_resources_test.dart` checks the committed files equal
/// these strings.
abstract final class AppIconResources {
  static const String _header = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_app_icons.dart from lib/splash/icon_geometry.dart. Do not edit by hand. -->
''';

  static const String _vectorOpen =
      '''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
''';

  /// `res/drawable/ic_launcher_background.xml`: the night gradient and the teal glow.
  static String background() {
    final top = _argb(SplashColors.tileTop);
    final bottom = _argb(SplashColors.background);
    final glow = SplashColors.star.withValues(alpha: 0.30);
    final glowOut = SplashColors.star.withValues(alpha: 0);
    return '$_header$_vectorOpen'
        '    <path android:pathData="M0 0H108V108H0Z">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient\n'
        '                android:type="linear"\n'
        '                android:startX="0"\n'
        '                android:startY="0"\n'
        '                android:endX="0"\n'
        '                android:endY="108">\n'
        '                <item android:offset="0" android:color="$top"/>\n'
        '                <item android:offset="1" android:color="$bottom"/>\n'
        '            </gradient>\n'
        '        </aapt:attr>\n'
        '    </path>\n'
        '    <path android:pathData="M0 0H108V108H0Z">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient\n'
        '                android:type="radial"\n'
        '                android:centerX="54"\n'
        '                android:centerY="30"\n'
        '                android:gradientRadius="48">\n'
        '                <item android:offset="0" android:color="${_argb(glow)}"/>\n'
        '                <item android:offset="1" android:color="${_argb(glowOut)}"/>\n'
        '            </gradient>\n'
        '        </aapt:attr>\n'
        '    </path>\n'
        '</vector>\n';
  }

  /// `res/drawable/ic_launcher_foreground.xml`: the art in full colour, in the adaptive placement.
  static String foreground() {
    final b = StringBuffer('$_header$_vectorOpen')..write(_groupOpen());
    _fill(b, 'star_square', AppIconGeometry.starSquare, SplashColors.star);
    _fill(b, 'star_diamond', AppIconGeometry.starDiamond, SplashColors.star);
    _fill(b, 'star_hole', AppIconGeometry.starHole, SplashColors.background);
    _fill(b, 'page_left', AppIconGeometry.pageLeft, SplashColors.pageLeft);
    _fill(b, 'page_right', AppIconGeometry.pageRight, SplashColors.pageRight);
    _stroke(
      b,
      'spine',
      AppIconGeometry.spine,
      SplashColors.pageInk,
      AppIconGeometry.spineWidth,
      round: false,
    );
    _stroke(
      b,
      'lines_left',
      AppIconGeometry.pagesLinesLeft,
      SplashColors.pageInk,
      AppIconGeometry.pageLinesWidth,
    );
    _stroke(
      b,
      'lines_right',
      AppIconGeometry.pagesLinesRight,
      SplashColors.pageInk,
      AppIconGeometry.pageLinesWidth,
    );
    _stroke(
      b,
      'gold_line',
      AppIconGeometry.goldLine,
      SplashColors.gold,
      AppIconGeometry.goldWidth,
    );
    b
      ..write('    </group>\n')
      ..write('</vector>\n');
    return b.toString();
  }

  /// `res/drawable/ic_launcher_monochrome.xml`: one colour (the launcher tints it), the star with its hole cut out.
  static String monochrome() {
    const white = Color(0xFFFFFFFF);
    final b = StringBuffer('$_header$_vectorOpen')..write(_groupOpen());
    _fill(
      b,
      'star',
      '${AppIconGeometry.monochromeStar} ${AppIconGeometry.starHole}',
      white,
      evenOdd: true,
    );
    _fill(b, 'page_left', AppIconGeometry.monochromePageLeft, white);
    _fill(b, 'page_right', AppIconGeometry.monochromePageRight, white);
    _stroke(
      b,
      'gold_line',
      AppIconGeometry.goldLine,
      white,
      AppIconGeometry.monochromeGoldWidth,
    );
    b
      ..write('    </group>\n')
      ..write('</vector>\n');
    return b.toString();
  }

  static String _groupOpen() {
    const p = AppIconGeometry.adaptive;
    return '    <group\n'
        '        android:pivotX="${_n(p.pivot.dx)}"\n'
        '        android:pivotY="${_n(p.pivot.dy)}"\n'
        '        android:scaleX="${_n(p.scale)}"\n'
        '        android:scaleY="${_n(p.scale)}"\n'
        '        android:translateY="${_n(p.shift.dy)}">\n';
  }

  static void _fill(
    StringBuffer b,
    String name,
    String data,
    Color color, {
    bool evenOdd = false,
  }) {
    b
      ..write('        <path\n')
      ..write('            android:name="$name"\n')
      ..write('            android:fillColor="${_argb(color)}"\n')
      ..write(evenOdd ? '            android:fillType="evenOdd"\n' : '')
      ..write('            android:pathData="$data"/>\n');
  }

  static void _stroke(
    StringBuffer b,
    String name,
    String data,
    Color color,
    double width, {
    bool round = true,
  }) {
    b
      ..write('        <path\n')
      ..write('            android:name="$name"\n')
      ..write('            android:strokeColor="${_argb(color)}"\n')
      ..write('            android:strokeWidth="${_n(width)}"\n')
      ..write(round ? '            android:strokeLineCap="round"\n' : '')
      ..write('            android:pathData="$data"/>\n');
  }

  /// `#AARRGGBB`, upper case, as Android reads it.
  static String _argb(Color c) {
    String h(double v) =>
        (v * 255).round().toRadixString(16).padLeft(2, '0').toUpperCase();
    return '#${h(c.a)}${h(c.r)}${h(c.g)}${h(c.b)}';
  }

  /// A number without a trailing `.0`.
  static String _n(double v) =>
      v == v.roundToDouble() ? v.toInt().toString() : v.toString();
}
